
-- Deploy ff2b_db:players to pg

BEGIN;

-- Informations complémentaires sur l'identité
ALTER TABLE persons
    ADD COLUMN alias TEXT,
    ADD COLUMN sex VARCHAR(30),
    ADD COLUMN birth_place INTEGER
        REFERENCES municipalities(id)
        ON DELETE SET NULL;

-- Profil joueur
CREATE TABLE players (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    person_id UUID NOT NULL UNIQUE
        REFERENCES persons(ff2b_id)
        ON DELETE RESTRICT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE players IS
    'Profil sportif associé à une personne de la FF2B';

COMMENT ON COLUMN players.person_id IS
    'Personne à laquelle appartient le profil joueur';


-- Informations médicales confidentielles
CREATE TABLE player_medical_information (
    player_id UUID PRIMARY KEY
        REFERENCES players(id)
        ON DELETE CASCADE,

    treating_doctor_name TEXT,
    treating_doctor_contact TEXT,
    allergies TEXT,
    blood_group VARCHAR(5),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE player_medical_information IS
    'Informations médicales confidentielles du joueur, à accès restreint';

COMMENT ON COLUMN player_medical_information.treating_doctor_name IS
    'Nom et prénom du médecin traitant';

COMMENT ON COLUMN player_medical_information.treating_doctor_contact IS
    'Téléphone ou email du médecin traitant';

COMMENT ON COLUMN player_medical_information.allergies IS
    'Allergies connues, si leur conservation est nécessaire';

COMMENT ON COLUMN player_medical_information.blood_group IS
    'Groupe sanguin, si sa conservation est nécessaire';


-- Types de contacts associés à un joueur
CREATE TYPE player_contact_type AS ENUM (
    'legal_representative',
    'emergency_contact'
);


CREATE TABLE player_contacts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    player_id UUID NOT NULL
        REFERENCES players(id)
        ON DELETE CASCADE,

    contact_type player_contact_type NOT NULL,

    -- Référence facultative à une personne déjà connue
    contact_person_id UUID
        REFERENCES persons(ff2b_id)
        ON DELETE RESTRICT,

    -- Coordonnées utiles pour un contact externe
    first_name TEXT,
    last_name TEXT,
    phone_number TEXT,
    email TEXT,
    relationship TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_player_contacts_data_present
        CHECK (
            contact_person_id IS NOT NULL
            OR (
                NULLIF(TRIM(first_name), '') IS NOT NULL
                AND NULLIF(TRIM(last_name), '') IS NOT NULL
                AND NULLIF(TRIM(phone_number), '') IS NOT NULL
            )
        )
);

COMMENT ON TABLE player_contacts IS
    'Représentants légaux et contacts à prévenir en urgence';

COMMENT ON COLUMN player_contacts.contact_type IS
    'Type de relation : représentant légal ou contact d''urgence';

COMMENT ON COLUMN player_contacts.contact_person_id IS
    'Référence vers persons si le contact est déjà connu de la FF2B';

COMMENT ON COLUMN player_contacts.relationship IS
    'Lien de parenté ou nature de la relation avec le joueur';


-- Index des clés étrangères utilisées pour les recherches
CREATE INDEX idx_player_contacts_player_id
    ON player_contacts(player_id);

CREATE INDEX idx_player_contacts_contact_person_id
    ON player_contacts(contact_person_id);

COMMIT;
