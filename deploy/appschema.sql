-- Validates score symmetry, completed-game completeness, and competition/team consistency.
CREATE OR REPLACE FUNCTION validate_game_integrity()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_game_id INTEGER;
    v_status GAME_STATUS;
    v_side_count INTEGER;
    v_result_count INTEGER;
BEGIN
    IF TG_TABLE_NAME = 'games' THEN
        v_game_id := COALESCE(NEW.id, OLD.id);
    ELSIF TG_TABLE_NAME = 'game_side' THEN
        v_game_id := COALESCE(NEW.game_id, OLD.game_id);
    ELSIF TG_OP = 'DELETE' AND TG_TABLE_NAME = 'game_side_result' THEN
        SELECT gs.game_id
        INTO v_game_id
        FROM game_side gs
        WHERE gs.id = OLD.game_side_id;
    ELSE
        SELECT gs.game_id
        INTO v_game_id
        FROM game_side_result gsr
        JOIN game_side gs ON gs.id = gsr.game_side_id
        WHERE gsr.game_side_id = COALESCE(NEW.game_side_id, OLD.game_side_id)
        LIMIT 1;
    END IF;

    SELECT g.status
    INTO v_status
    FROM games g
    WHERE g.id = v_game_id;

    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM game_side gs
        JOIN teams t ON t.id = gs.team_id
        JOIN games g ON g.id = gs.game_id
        WHERE gs.game_id = v_game_id
          AND g.competition_id IS NOT NULL
          AND t.competition_id <> g.competition_id
    ) THEN
        RAISE EXCEPTION
            'A team used in game % must belong to the same competition as the game',
            v_game_id;
    END IF;

    IF (
        SELECT COUNT(*)
        FROM game_side_result r
        JOIN game_side gs ON gs.id = r.game_side_id
        WHERE gs.game_id = v_game_id
    ) = 2
    AND EXISTS (
        SELECT 1
        FROM game_side gs1
        JOIN game_side_result r1 ON r1.game_side_id = gs1.id
        JOIN game_side gs2
          ON gs2.game_id = gs1.game_id
         AND gs2.side_number <> gs1.side_number
        JOIN game_side_result r2 ON r2.game_side_id = gs2.id
        WHERE gs1.game_id = v_game_id
          AND (
              r1.nieshs_scored <> r2.nieshs_conceded
              OR r1.nieshs_conceded <> r2.nieshs_scored
          )
    ) THEN
        RAISE EXCEPTION
            'Scores for the two sides of game % must be reciprocal',
            v_game_id;
    END IF;

    IF v_status = 'completed' THEN
        SELECT COUNT(*) INTO v_side_count
        FROM game_side
        WHERE game_id = v_game_id;

        SELECT COUNT(*) INTO v_result_count
        FROM game_side_result r
        JOIN game_side gs ON gs.id = r.game_side_id
        WHERE gs.game_id = v_game_id;

        IF v_side_count <> 2 OR v_result_count <> 2 THEN
            RAISE EXCEPTION
                'Completed game % must have exactly two sides and two results',
                v_game_id;
        END IF;

        IF EXISTS (
            SELECT 1
            FROM game_side gs
            WHERE gs.game_id = v_game_id
              AND (
                  (
                      gs.person_id IS NOT NULL
                      AND NOT EXISTS (
                          SELECT 1
                          FROM game_participant gp
                          WHERE gp.game_side_id = gs.id
                            AND gp.person_id = gs.person_id
                      )
                  )
                  OR
                  (
                      gs.team_id IS NOT NULL
                      AND NOT EXISTS (
                          SELECT 1
                          FROM game_participant gp
                          WHERE gp.game_side_id = gs.id
                      )
                  )
              )
        ) THEN
            RAISE EXCEPTION
                'Every side of completed game % must have valid participants',
                v_game_id;
        END IF;
    END IF;

    RETURN NULL;
END;
$$;

-- Validates participant uniqueness, individual-side identity, and team membership.
CREATE OR REPLACE FUNCTION validate_game_participant()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_game_id INTEGER;
    v_side_person UUID;
    v_team_id INTEGER;
BEGIN
    IF TG_TABLE_NAME = 'game_participant' THEN
        IF TG_OP = 'DELETE' THEN
            RETURN NULL;
        END IF;

        SELECT gs.game_id, gs.person_id, gs.team_id
        INTO v_game_id, v_side_person, v_team_id
        FROM game_side gs
        WHERE gs.id = NEW.game_side_id;

        IF v_team_id IS NULL AND v_side_person IS DISTINCT FROM NEW.person_id THEN
            RAISE EXCEPTION
                'An individual game side can only contain its declared person';
        END IF;

        IF v_team_id IS NOT NULL
           AND NOT EXISTS (
               SELECT 1
               FROM team_members tm
               WHERE tm.team_id = v_team_id
                 AND tm.person_id = NEW.person_id
           ) THEN
            RAISE EXCEPTION
                'Person % is not a member of team %',
                NEW.person_id, v_team_id;
        END IF;

        IF EXISTS (
            SELECT 1
            FROM game_participant gp
            JOIN game_side other_side ON other_side.id = gp.game_side_id
            WHERE other_side.game_id = v_game_id
              AND gp.person_id = NEW.person_id
              AND gp.id <> NEW.id
        ) THEN
            RAISE EXCEPTION
                'Person % cannot participate on both sides of game %',
                NEW.person_id, v_game_id;
        END IF;
    ELSE
        SELECT gs.game_id, gs.person_id, gs.team_id
        INTO v_game_id, v_side_person, v_team_id
        FROM game_side gs
        WHERE gs.id = COALESCE(NEW.id, OLD.id);

        IF v_side_person IS NOT NULL
           AND EXISTS (
               SELECT 1
               FROM game_participant gp
               WHERE gp.game_side_id = COALESCE(NEW.id, OLD.id)
                 AND gp.person_id IS DISTINCT FROM v_side_person
           ) THEN
            RAISE EXCEPTION
                'An individual game side cannot contain another person';
        END IF;

        IF v_team_id IS NOT NULL
           AND EXISTS (
               SELECT 1
               FROM game_participant gp
               WHERE gp.game_side_id = COALESCE(NEW.id, OLD.id)
                 AND NOT EXISTS (
                     SELECT 1
                     FROM team_members tm
                     WHERE tm.team_id = v_team_id
                       AND tm.person_id = gp.person_id
                 )
           ) THEN
            RAISE EXCEPTION
                'Every participant on a team side must belong to that team';
        END IF;

        IF EXISTS (
            SELECT 1
            FROM game_participant gp
            JOIN game_side other_side ON other_side.id = gp.game_side_id
            WHERE gp.game_side_id = COALESCE(NEW.id, OLD.id)
              AND EXISTS (
                  SELECT 1
                  FROM game_participant other_gp
                  JOIN game_side other_game_side
                    ON other_game_side.id = other_gp.game_side_id
                  WHERE other_game_side.game_id = v_game_id
                    AND other_gp.person_id = gp.person_id
                    AND other_gp.game_side_id <> gp.game_side_id
              )
        ) THEN
            RAISE EXCEPTION
                'A person cannot participate on both sides of game %',
                v_game_id;
        END IF;
    END IF;

    RETURN NULL;
END;
$$;

-- Prevents removing or changing a team member while that person is used in a game.
CREATE OR REPLACE FUNCTION validate_team_membership_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM game_participant gp
        JOIN game_side gs ON gs.id = gp.game_side_id
        WHERE (gs.team_id = OLD.team_id OR gs.team_id = NEW.team_id)
          AND gp.person_id = COALESCE(OLD.person_id, NEW.person_id)
          AND NOT EXISTS (
              SELECT 1
              FROM team_members tm
              WHERE tm.team_id = gs.team_id
                AND tm.person_id = gp.person_id
          )
    ) THEN
        RAISE EXCEPTION
            'A team member cannot be removed while participating in a game';
    END IF;

    RETURN NULL;
END;
$$;

-- Prevents changing a team's competition while it is used in another competition.
CREATE OR REPLACE FUNCTION validate_team_competition_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM game_side gs
        JOIN games g ON g.id = gs.game_id
        WHERE gs.team_id = COALESCE(NEW.id, OLD.id)
          AND g.competition_id IS NOT NULL
          AND g.competition_id <> COALESCE(NEW.competition_id, OLD.competition_id)
    ) THEN
        RAISE EXCEPTION
            'A team competition cannot be changed while the team is used in a game';
    END IF;

    RETURN NULL;
END;
$$;

