	-- Number of nieshs conceded.
	"nieshs_conceded" SMALLINT NOT NULL CHECK ("nieshs_conceded" >= 0),
	-- Result for this game side.
	"result" SMALLINT GENERATED ALWAYS AS (
		CASE
			WHEN "nieshs_scored" > "nieshs_conceded" THEN 1
